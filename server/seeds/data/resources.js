function inferType(url) {
    if (/youtube\.com|youtu\.be/i.test(url)) return 'video';
    if (/\.pdf($|\?)/i.test(url)) return 'pdf';
    if (/vimeo\.com/i.test(url)) return 'video';
    return 'article';
}

